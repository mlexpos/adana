"""Forward+backward timings of the pieces of one Enoki training micro-batch on one GPU, to price implementation-only speedups.

At a given size (default 24 heads: d 1536, 18 layers, MLP 6144, head dim 64) and micro-batch (16 x 2048 tokens), under bf16 autocast
and torch.compile as in training:
  attention core   causal attention on (B, H, T, 64) bf16, every available implementation: SDPA's flash (FlashAttention-2), cuDNN and
                   memory-efficient backends; FlexAttention (Triton, generated by torch); the Triton tutorial's fused attention if
                   --triton_attn points at it; flash_attn (FA2 package) and flash_attn_interface (FA3) if installed.  TFLOP/s counts
                   causal FLOPs (forward 2 B H T^2 D, backward 2.5 x forward).  Each is checked against SDPA's math backend.
  qk-norm + rope   Enoki's QK-LayerNorm and fp32 RoPE on q and k (the elementwise part of the attention block), against a single
                   read and write of q and k at memory bandwidth (the floor a fused kernel could reach).
  attention block  EnokiAttention (projections + qk-norm + rope + core + output projection) with each SDPA backend.
  MLP              EnokiMLP (Linear, GELU, Linear) and the same with the activation removed (its two GEMMs alone): the difference
                   bounds what fusing GELU into a GEMM can save.
  loss             the training loss (chunked_cross_entropy with z-loss, 256-token chunks) against one lm_head GEMM forward and
                   backward (the floor of any fused loss that keeps bf16 logits).
  block            one EnokiBlock; x n_layer + loss approximates the model's compute per micro-batch.
usage: python scripts/bench_components.py [--heads 24] [--micro 16] [--triton_attn path/to/06-fused-attention.py] [--json out.json]
"""
import argparse
import importlib.util
import json
import math
import os
import sys
from types import SimpleNamespace

import torch
import torch.nn.functional as F
from torch.nn.attention import SDPBackend, sdpa_kernel

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src"))
from models.enoki import EnokiAttention, EnokiBlock, EnokiMLP, precompute_freqs_cis, apply_rotary_emb  # noqa: E402
from models.chunked_loss import chunked_cross_entropy  # noqa: E402

DIMS = {12: (9, 768), 16: (12, 1024), 20: (15, 1280), 24: (18, 1536), 28: (21, 1792), 32: (24, 2048)}
DEV = "cuda"


def timeit(fn, warm=5, iters=20):
    for _ in range(warm):
        fn()
    torch.cuda.synchronize()
    s, e = torch.cuda.Event(enable_timing=True), torch.cuda.Event(enable_timing=True)
    s.record()
    for _ in range(iters):
        fn()
    e.record()
    torch.cuda.synchronize()
    return s.elapsed_time(e) / iters            # ms


def fwd_bwd(f, inputs, params=()):
    """A closure running f(*inputs) forward and backward (sum of outputs as the loss), clearing grads first."""
    def run():
        for t in list(inputs) + list(params):
            t.grad = None
        out = f(*inputs)
        out = out[0] if isinstance(out, tuple) else out
        out.float().sum().backward() if out.dim() else out.backward()
    return run


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--heads", type=int, default=24)
    ap.add_argument("--micro", type=int, default=16)
    ap.add_argument("--seq", type=int, default=2048)
    ap.add_argument("--triton_attn", default=None, help="path to the Triton tutorial 06-fused-attention.py")
    ap.add_argument("--json", default=None)
    a = ap.parse_args()
    L, d = DIMS[a.heads]
    H, D, B, T, V = a.heads, 64, a.micro, a.seq, 50304
    torch.manual_seed(0)
    torch.backends.cuda.matmul.allow_tf32 = True
    cfg = SimpleNamespace(n_embd=d, n_head=H, qkv_dim=D, bias=False, dropout=0.0, no_qknorm=False, mlp_hidden_dim=4 * d, moe=False,
                          residual_stream_scalar=1.0, parallel_block=False, sequence_length=T, multiple_of=256)
    peak = {"H100 NVL": 835e12, "H100 80GB HBM3": 989e12}.get(torch.cuda.get_device_name(0).replace("NVIDIA ", ""), float("nan"))
    R = dict(gpu=torch.cuda.get_device_name(0), torch=torch.__version__, heads=H, layers=L, d=d, B=B, T=T, results={})
    out = R["results"]

    def report(name, ms, flops=None, extra=""):
        tf = f"  {flops / ms / 1e9:7.1f} TFLOP/s ({flops / ms / 1e9 / (peak / 1e12):5.1%} of peak)" if flops else ""
        print(f"{name:44s} {ms:8.3f} ms{tf}{extra}", flush=True)
        out[name] = dict(ms=ms, tflops=(flops / ms / 1e9 if flops else None))

    # ------------------------------------------------------------------ attention core
    print(f"== {R['gpu']}, torch {torch.__version__}; {H} heads, d {d}, {L} layers, micro-batch {B} x {T}")
    print("-- attention core, causal, forward + backward")
    q, k, v = (torch.randn(B, H, T, D, device=DEV, dtype=torch.bfloat16, requires_grad=True) for _ in range(3))
    att_flops = 2 * B * H * T * T * D * 3.5       # causal: forward 4 B H T^2 D / 2, backward 2.5 x
    go = torch.randn(B, H, T, D, device=DEV, dtype=torch.bfloat16)
    with sdpa_kernel(SDPBackend.MATH):
        ref = F.scaled_dot_product_attention(q.float(), k.float(), v.float(), is_causal=True)
        ref.backward(go.float())
    gref = [t.grad.clone() for t in (q, k, v)]

    def check(fn):
        for t in (q, k, v):
            t.grad = None
        y = fn(q, k, v)
        y.backward(go)
        err = max(float((y.float() - ref).abs().max()), *(float((t.grad.float() - g).abs().max()) for t, g in zip((q, k, v), gref)))
        return err

    def core(fn, name):
        try:
            err = check(fn)

            def run():
                for t in (q, k, v):
                    t.grad = None
                fn(q, k, v).backward(go)
            report(name, timeit(run), att_flops, f"   max err vs fp32 {err:.2e}")
        except Exception as e:  # noqa: BLE001
            print(f"{name:44s} unavailable: {type(e).__name__}: {str(e)[:120]}")

    for be, nm in ((SDPBackend.FLASH_ATTENTION, "sdpa flash (FA2)"), (SDPBackend.CUDNN_ATTENTION, "sdpa cuDNN"),
                   (SDPBackend.EFFICIENT_ATTENTION, "sdpa mem-efficient")):
        def f(q_, k_, v_, be=be):
            with sdpa_kernel(be):
                return F.scaled_dot_product_attention(q_, k_, v_, is_causal=True)
        core(f, nm)
    try:
        from torch.nn.attention.flex_attention import create_block_mask, flex_attention
        bm = create_block_mask(lambda b, h, qi, ki: qi >= ki, None, None, T, T, device=DEV)
        flex = torch.compile(flex_attention)
        core(lambda q_, k_, v_: flex(q_, k_, v_, block_mask=bm), "flex_attention (Triton)")
    except Exception as e:  # noqa: BLE001
        print(f"flex_attention unavailable: {e!r}"[:160])
    if a.triton_attn:
        spec = importlib.util.spec_from_file_location("tri_attn", a.triton_attn)
        mod = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(mod)
        att = mod.attention
        import inspect
        ps = list(inspect.signature(mod._attention.forward).parameters)
        if len(ps) >= 7:    # (ctx, q, k, v, causal, sm_scale, <switch>): USE_TMA (Triton 3.3) or warp_specialize (later)
            core(lambda q_, k_, v_: att(q_, k_, v_, True, 1 / math.sqrt(D), False), f"triton tutorial, {ps[6]}=False")
            core(lambda q_, k_, v_: att(q_, k_, v_, True, 1 / math.sqrt(D), True), f"triton tutorial, {ps[6]}=True")
        else:
            core(lambda q_, k_, v_: att(q_, k_, v_, True, 1 / math.sqrt(D)), "triton tutorial")
    for modname, nm in (("flash_attn", "flash_attn package (FA2)"), ("flash_attn_interface", "flash_attn_interface (FA3)")):
        if importlib.util.find_spec(modname):
            m = importlib.import_module(modname)
            fa = m.flash_attn_func
            def f(q_, k_, v_, fa=fa):
                y = fa(q_.transpose(1, 2), k_.transpose(1, 2), v_.transpose(1, 2), causal=True)
                y = y[0] if isinstance(y, tuple) else y
                return y.transpose(1, 2)
            core(f, nm)
        else:
            print(f"{nm:44s} not installed")
    del q, k, v, go, ref, gref

    # ------------------------------------------------------------------ qk-norm + rope (elementwise part of attention)
    print("-- QK-LayerNorm + RoPE on q and k (Enoki's code, compiled), forward + backward")
    attn = EnokiAttention(cfg).to(DEV)
    fc = precompute_freqs_cis(D, T).to(DEV)
    qk = [torch.randn(B, T, H, D, device=DEV, dtype=torch.bfloat16, requires_grad=True) for _ in range(2)]

    def qkrope(q_, k_):
        q_, k_ = attn.q_layernorm(q_), attn.k_layernorm(k_)
        q_, k_ = apply_rotary_emb(q_, k_, fc)
        return (q_.to(torch.bfloat16).float().sum() + k_.to(torch.bfloat16).float().sum())
    f = torch.compile(qkrope)
    with torch.autocast("cuda", torch.bfloat16):
        ms = timeit(fwd_bwd(f, qk, list(attn.parameters())))
    bytes_min = 2 * (B * T * H * D * 2) * 2 * 2       # q and k, bf16, read + write, forward and backward
    bw = {"H100 NVL": 3.9e12, "H100 80GB HBM3": 3.35e12}.get(R["gpu"].replace("NVIDIA ", ""), float("nan"))
    report("qk-norm + rope (current)", ms, extra=f"   memory floor ~{bytes_min / bw * 1e3:.3f} ms")
    del qk

    # ------------------------------------------------------------------ attention block, MLP, loss, block
    x = torch.randn(B, T, d, device=DEV, dtype=torch.float32, requires_grad=True)
    print("-- attention block (EnokiAttention, compiled), forward + backward, by SDPA backend")
    for be, nm in ((SDPBackend.FLASH_ATTENTION, "flash (FA2)"), (SDPBackend.CUDNN_ATTENTION, "cuDNN")):
        torch._dynamo.reset()
        fa = torch.compile(lambda x_, be=be: _with_backend(be, attn, x_, fc))
        try:
            with torch.autocast("cuda", torch.bfloat16):
                report(f"attention block, {nm}", timeit(fwd_bwd(fa, [x], list(attn.parameters()))),
                       2 * B * T * d * 4 * d * 3 + att_flops)
        except Exception as e:  # noqa: BLE001
            print(f"attention block, {nm}: {type(e).__name__}: {str(e)[:120]}")
    print("-- MLP (EnokiMLP, compiled), forward + backward")
    mlp = EnokiMLP(cfg).to(DEV)
    mlp_flops = 2 * B * T * d * 4 * d * 2 * 3
    torch._dynamo.reset()
    fm = torch.compile(lambda x_: mlp(x_)[0])
    with torch.autocast("cuda", torch.bfloat16):
        report("MLP, GELU (current)", timeit(fwd_bwd(fm, [x], list(mlp.parameters()))), mlp_flops)
    act = mlp.activation
    mlp.activation = torch.nn.Identity()
    torch._dynamo.reset()
    fm = torch.compile(lambda x_: mlp(x_)[0])
    with torch.autocast("cuda", torch.bfloat16):
        report("MLP, no activation (GEMMs only)", timeit(fwd_bwd(fm, [x], list(mlp.parameters()))), mlp_flops)
    mlp.activation = act
    print("-- loss, forward + backward")
    W = (torch.randn(V, d, device=DEV) * 0.02).requires_grad_(True)
    tgt = torch.randint(0, V, (B, T), device=DEV)
    hb = torch.randn(B, T, d, device=DEV, dtype=torch.bfloat16, requires_grad=True)
    head_flops = 2 * B * T * d * V * 3
    with torch.autocast("cuda", torch.bfloat16):
        report("loss, chunked CE + z-loss (current)", timeit(fwd_bwd(
            lambda h: chunked_cross_entropy(h, W, tgt, compute_z_loss=True, z_loss_coeff=1e-4)[0], [hb], [W])), head_flops)
        torch._dynamo.reset()
        fh = torch.compile(lambda h: F.linear(h, W).float().square().mean())
        report("lm_head GEMMs alone (floor)", timeit(fwd_bwd(fh, [hb], [W])), head_flops)
        torch._dynamo.reset()
        fl = torch.compile(lambda h: _plain_ce(h, W, tgt))
        try:
            report("loss, one-shot compiled CE + z-loss", timeit(fwd_bwd(fl, [hb], [W])), head_flops)
        except Exception as e:  # noqa: BLE001
            print(f"one-shot loss: {type(e).__name__}: {str(e)[:120]}")
    del W, hb
    print("-- one EnokiBlock (compiled), forward + backward")
    blk = EnokiBlock(cfg).to(DEV)
    torch._dynamo.reset()
    fb = torch.compile(lambda x_: blk(x_, fc)[0])
    with torch.autocast("cuda", torch.bfloat16):
        ms_blk = timeit(fwd_bwd(fb, [x], list(blk.parameters())))
    report("block", ms_blk, 2 * B * T * (12 * d * d) * 3 + att_flops)
    loss_ms = out["loss, chunked CE + z-loss (current)"]["ms"]
    est = L * ms_blk + loss_ms
    print(f"-- per micro-batch: {L} blocks + loss = {est:.1f} ms  ({L} x {ms_blk:.2f} + {loss_ms:.2f})")
    R["est_microbatch_ms"] = est
    if a.json:
        json.dump(R, open(a.json, "w"), indent=1)


def _with_backend(be, attn, x, fc):
    with sdpa_kernel(be):
        return attn(x, fc)


def _plain_ce(h, W, tgt):
    logits = F.linear(h, W).float().reshape(-1, W.shape[0])
    ce = F.cross_entropy(logits, tgt.reshape(-1))
    z = torch.logsumexp(logits, -1).square().mean()
    return ce + 1e-4 * z


if __name__ == "__main__":
    main()
